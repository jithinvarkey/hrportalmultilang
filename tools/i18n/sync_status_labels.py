"""
Regenerates backend/lang/<locale>/status.php from the frontend STATUS dictionary
(frontend/src/assets/i18n/<locale>/common.json), so the UI and emails use the same status wording.

    python tools/i18n/sync_status_labels.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]


def php_str(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


for locale in ("en", "ar"):
    common = json.loads((ROOT / f"frontend/src/assets/i18n/{locale}/common.json").read_text(encoding="utf-8"))
    statuses = common["STATUS"]
    width = max(len(k) for k in statuses) + 2
    lines = [
        "<?php",
        "",
        "// GENERATED by tools/i18n/sync_status_labels.py from frontend/src/assets/i18n/%s/common.json (STATUS)." % locale,
        "// Edit the JSON file and re-run the script instead of editing this file.",
        "// Usage: __('status.' . $code)  or  \\App\\Support\\Locale\\StatusLabel::for($code)",
        "return [",
    ]
    for code in sorted(statuses):
        lines.append(f"    {php_str(code).ljust(width)} => {php_str(statuses[code])},")
    lines += ["];", ""]
    out = ROOT / f"backend/lang/{locale}/status.php"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)} ({len(statuses)} statuses)")
